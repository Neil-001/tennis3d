// Mixed campaign kinds use the shared server, selector and source-qualified routes.
import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const artifacts = process.env.DASHBOARD_ARTIFACTS || path.join(root, 'viewer/test-artifacts');
await mkdir(artifacts, {recursive:true});
const directory = await mkdtemp(path.join(artifacts, 'dashboard-throughput-'));
const run = path.join(directory, 'throughput'), archive = path.join(directory, 'accuracy');
const python = process.env.DASHBOARD_PYTHON || path.join(root, '.venv/bin/python');
const env = {...process.env, PYTHONPATH:root};
execFileSync(python, ['tests/throughput_dashboard_fixture.py', run], {cwd:root, env});
execFileSync(python, ['tests/dashboard_fixture.py', archive, 'multirun-archive'], {cwd:root, env});
const files = async () => {
  const values = {};
  for (const entry of await readdir(directory,{recursive:true,withFileTypes:true})) if (entry.isFile()) {
    const filename = path.join(entry.parentPath || entry.path, entry.name);
    values[path.relative(directory,filename)] = (await readFile(filename)).toString('base64');
  }
  return values;
};
const before = await files();
const server = spawn(python, ['-m','tennis3d','dashboard','--run',run,'--kind','throughput','--archive-run',archive,'--port','0'], {cwd:root,env,stdio:['ignore','pipe','pipe']});
const base = await new Promise((resolve,reject) => {
  const timer = setTimeout(() => reject(Error('server did not start')),10000);
  server.stdout.on('data',data => { const match = data.toString().match(/http:\/\/127\.0\.0\.1:\d+/); if(match) { clearTimeout(timer); resolve(match[0]); } });
  server.on('exit',code => {clearTimeout(timer); reject(Error(`server exited ${code}`));});
});
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1280,height:1000}}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#throughput-view').hidden === false);
  const key = await page.locator('#segment').inputValue();
  assert.match(key,/^throughput:/);
  assert.equal(await page.locator('#accuracy-view').isVisible(),false);
  assert.match(await page.locator('#best').textContent(),/Incumbent trial: 000001/);
  assert.match(await page.locator('#throughput-counts').textContent(),/1 kept.*1 discarded.*0 failed/);
  assert.match(await page.locator('#qualification').textContent(),/baseline elapsed_s pairs \(s\)/);
  for (const id of ['protocol-details','qualification-details','diagnostic-details']) assert.equal(await page.locator(`#${id}`).getAttribute('open'),null,`${id} starts collapsed`);
  assert.equal(await page.locator('#throughput-identity').isVisible(),false);
  assert.doesNotMatch(await page.locator('#best').textContent(),/1{64}/);
  assert.match(await page.locator('#throughput-facts').textContent(),/RTX 2080 Ti.*4 CPUs.*32\.0 GiB.*128 updates.*6144 windows.*batch 48.*250 frames/s);
  assert.match(await page.locator('#throughput-facts').textContent(),/Stream noise 2\.0%.*sustained noise 2\.0%/s);
  assert.match(await page.locator('#throughput-trials').textContent(),/0\.900.*0\.950/s);
  await page.getByRole('button',{name:'000002',exact:true}).click();
  await page.waitForFunction(() => details?.trial?.trial === '000002');
  assert.match(await page.locator('#workloads').textContent(),/elapsed_s.*4\.750.*5\.000.*0\.950/s);
  assert.match(await page.locator('#workloads').textContent(),/stream_s.*3\.800.*4\.000.*0\.950/s);
  assert.match(await page.locator('#throughput-diagnostics').textContent(),/stall_p95_s.*0\.03/s);
  assert.match(await page.locator('#throughput-diagnostics').textContent(),/windows_per_second.*1293/s);
  assert.doesNotMatch(await page.locator('body').textContent(),/private_path|credential\/location/);
  assert.equal(await page.locator('#history').isVisible(),false,'speed data cannot enter accuracy chart');
  assert.match(await page.locator("#throughput-latest").textContent(),/Trial 000002 candidate pair means: elapsed 4\.750 s.*stream 3\.800 s.*sustained 2\.850 s.*1293\.5 windows\/s/);
  assert.match(await page.locator('#diagnostic-summary').textContent(),/Setup: 0\.200 s.*Stream: 3\.800 s.*Sustained: 2\.850 s.*1293\.5 windows\/s.*Stall mean: 0\.010 s.*Max pair stall p95: 0\.030 s.*RAM: 9\.8 KiB/s);
  assert.match(await page.locator('#throughput-accounting').textContent(),/compute 150\.000 s.*queue 25\.000 s.*reserved cap 1800\.000 s/);
  assert.equal(await page.locator('#throughput-diagnostics').isVisible(),false);
  await page.locator('#diagnostic-details summary').click();
  assert.equal(await page.locator('#throughput-diagnostics').isVisible(),true);
  assert.match(await page.locator('#throughput-diagnostics').textContent(),/2{64}/,'full hashes remain copyable');
  await page.locator('#diagnostic-details summary').click();
  await page.locator('#protocol-details summary').click();
  assert.match(await page.locator('#throughput-identity').textContent(),/1{64}/);
  await page.locator('#protocol-details summary').click();
  await page.screenshot({path:path.join(artifacts,'dashboard-throughput.png'),fullPage:true});
  await page.locator("h1").scrollIntoViewIfNeeded();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => { window.scrollTo(0,0); requestAnimationFrame(resolve); })));
  assert.equal(await page.evaluate(() => window.scrollY),0);
  await page.screenshot({path:path.join(artifacts,"dashboard-throughput-viewport.png")});
  const archiveKey = await page.locator('#segment option').first().getAttribute('value');
  await page.selectOption('#segment',archiveKey);
  assert.equal(await page.locator('#throughput-view').isVisible(),false);
  assert.equal(await page.locator('#history').isVisible(),true);
  await page.getByRole('button',{name:'reference-001',exact:true}).click();
  await page.locator('#compare-best').check();
  await page.waitForFunction(() => details?.metrics?.campaign === 'multirun-archive' && comparison?.data?.metrics?.campaign === 'multirun-archive');
  assert.match(await page.locator('#best').textContent(),/12\.000 m/);
  await page.waitForTimeout(2200);
  assert.equal(await page.locator('#segment').inputValue(),archiveKey);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#segment').value.startsWith('archive:'));
  await page.selectOption('#segment',key);
  await page.waitForFunction(() => details?.trial?.kind === 'throughput');
  assert.equal(await page.locator('#curve').isVisible(),false);
  assert.equal(await page.evaluate(() => comparison), null);
  assert.deepEqual(errors,[]);
  assert.deepEqual(await files(),before, "GETs leave all artifacts untouched");
  const log = path.join(run,"journal.jsonl"), raw = await readFile(log);
  await writeFile(log, Buffer.concat([raw,Buffer.from("{torn")]));
  await page.waitForFunction(() => document.querySelector("#connection").textContent.includes("stale/incomplete"));
  assert.match(await page.locator("#best").textContent(),/000001/);
  await writeFile(log,raw);
  await page.waitForFunction(() => !document.querySelector("#warning").textContent);
  console.log("Throughput browser passed: default kind, metric units, paired comparison, recorded retention, accuracy archive and comparison, durable selection, stale mirror recovery and unchanged artifacts.");
} finally { await browser.close(); server.kill('SIGTERM'); }
